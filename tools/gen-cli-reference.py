#!/usr/bin/env python3
"""Generate docs/cli-reference.md deterministically from `brain --help`.

Walks the whole command tree recursively and renders every page: the about
line, usage, subcommands and options — in the order clap prints them. The
output contains no timestamps, versions or paths, so regenerating the file
after a help-text change is the only source of diffs.

Usage: python3 tools/gen-cli-reference.py [--check]
  --check  print nothing on success; exit 1 when the committed reference is
           stale (tests/test_cli_reference.py runs it against a built binary).
The binary is taken from $BRAIN_REF_BIN or CARGO_TARGET_DIR, else ./target/debug.
"""
import os
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = pathlib.Path("docs/cli-reference.md")


def resolve_binary() -> str:
    for candidate in (
        os.environ.get("BRAIN_REF_BIN"),
        os.environ.get("CARGO_TARGET_DIR") and
        os.path.join(os.environ["CARGO_TARGET_DIR"], "debug", "brain"),
        str(ROOT / "target" / "debug" / "brain"),
    ):
        if candidate and os.path.isfile(candidate) and os.access(candidate, os.X_OK):
            return candidate
    sys.exit("brain binary not found; build it or set BRAIN_REF_BIN")


def help_text(binary: str, path: list) -> str:
    # clap displays the current env value beside --offline. Help must be
    # identical in an offline verification sandbox and a normal shell.
    env = dict(os.environ)
    env.pop("BRAIN_OFFLINE", None)
    result = subprocess.run([binary, *path, "--help"], capture_output=True, text=True, env=env)
    if result.returncode != 0:
        sys.exit(f"brain {' '.join(path)} --help failed: {result.stderr}")
    return result.stdout


def subcommand_names(text: str) -> list:
    """Names from the Commands section, excluding clap's own `help`."""
    names, in_commands = [], False
    for line in text.splitlines():
        if line.strip().lower().startswith("commands:"):
            in_commands = True
            continue
        if in_commands:
            if not line.strip():
                break
            match = re.match(r"\s+(\S+)\s{2,}", line)
            if match and match.group(1) != "help":
                names.append(match.group(1))
    return names


def clean_usage(text: str, path: list) -> str:
    """Rewrite the binary name and absolute paths out of the usage line."""
    usage = re.search(r"^Usage:\s+.*$", text, re.MULTILINE)
    if not usage:
        return ""
    line = usage.group(0)
    line = line.replace(os.path.basename(sys.executable) + " ", "")  # paranoia
    line = re.sub(r"Usage:\s+\S+", "Usage: brain", line, count=1)
    if path:
        line = line.replace(f"brain {' '.join(path)}", f"brain {' '.join(path)}", 1)
    return line


def clean_paths(text: str) -> str:
    """The help pages never contain absolute paths; nothing to scrub."""
    return text


def render_page(out: list, binary: str, path: list) -> None:
    text = help_text(binary, path)
    title = "brain" if not path else "brain " + " ".join(path)
    out.append(f"### `{title}`")
    out.append("")
    about = text.split("Usage:")[0].strip()
    if about:
        out.append(about)
        out.append("")
    usage = clean_usage(text, path)
    if usage:
        out.append("```console")
        out.append(usage)
        out.append("```")
        out.append("")
    body = text.split("Usage:", 1)[1] if "Usage:" in text else text
    body = body.split("Usage:", 1)[-1]
    body = re.sub(r"^.*?\n", "", body, count=1)  # drop the usage line itself
    body = clean_paths(body).strip("\n")
    if body:
        out.append("```text")
        out.append(body)
        out.append("```")
        out.append("")
    for name in subcommand_names(text):
        render_page(out, binary, path + [name])


def generate() -> str:
    binary = resolve_binary()
    root_help = help_text(binary, [])
    out = [
        "<!-- Generated by tools/gen-cli-reference.py from `brain --help`; do not edit. -->",
        "",
        "# CLI reference",
        "",
        "Every command and option, generated deterministically from the binary's",
        "own `--help` output. Regenerate with",
        "`python3 tools/gen-cli-reference.py` after changing a help text.",
        "",
    ]
    about = root_help.split("Usage:")[0].strip()
    if about:
        out += [about, ""]
    usage = clean_usage(root_help, [])
    if usage:
        out += ["```console", usage, "```", ""]
    body = root_help.split("Usage:", 1)[1]
    body = re.sub(r"^.*?\n", "", body, count=1).strip("\n")
    if body:
        out += ["```text", body, "```", ""]
    for name in subcommand_names(root_help):
        render_page(out, binary, [name])
    # clap may indent blank lines in wrapped help; keep generated Markdown clean.
    return "\n".join(line.rstrip() for line in "\n".join(out).split("\n")) + "\n"


def main() -> int:
    content = generate()
    if "--check" in sys.argv:
        committed = (ROOT / TARGET).read_text(encoding="utf-8")
        if committed != content:
            print("docs/cli-reference.md is stale; regenerate with"
                  " python3 tools/gen-cli-reference.py", file=sys.stderr)
            return 1
        return 0
    (ROOT / TARGET).write_text(content, encoding="utf-8")
    print(f"wrote {TARGET} ({len(content)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
