//! Storage-neutral embedding contract and optional local backends.

#[cfg(feature = "model2vec")]
use std::fs;
#[cfg(feature = "model2vec")]
use std::path::{Path, PathBuf};

use thiserror::Error;

/// Default multilingual Model2Vec model identifier.
pub const DEFAULT_MODEL2VEC_MODEL: &str = "minishlab/potion-multilingual-128M";

/// Model2Vec model selected for text containing only English/ASCII letters.
pub const DEFAULT_ENGLISH_MODEL2VEC_MODEL: &str = "minishlab/potion-base-8M";

/// Advertised first-download size for the multilingual model.
pub const DEFAULT_MODEL2VEC_DOWNLOAD_BYTES: u64 = 507_000_000;

/// Advertised first-download size for the compact English model.
pub const DEFAULT_ENGLISH_MODEL2VEC_DOWNLOAD_BYTES: u64 = 30_000_000;

/// Vector width produced by the configured Model2Vec model.
pub const DEFAULT_MODEL2VEC_DIMENSIONS: usize = 256;

/// Failure produced while loading or invoking an embedding backend.
#[derive(Debug, Error)]
pub enum EmbeddingError {
    /// Backend initialization or inference failed.
    #[error("embedding backend failed: {0}")]
    Backend(String),

    /// Model files are absent and downloads are disabled or unavailable.
    #[error("embedding model unavailable: {0}")]
    Unavailable(String),

    /// A backend returned no vector or a vector with an unexpected width.
    #[error("embedding backend returned {found} dimensions; expected {expected}")]
    Dimensions {
        /// Width advertised by the backend.
        expected: usize,
        /// Width actually returned.
        found: usize,
    },
}

/// Chooses the measured English or multilingual Model2Vec model for text.
#[must_use]
pub fn model_id_for_text(text: &str) -> &'static str {
    if text
        .chars()
        .any(|character| character.is_alphabetic() && !character.is_ascii())
    {
        DEFAULT_MODEL2VEC_MODEL
    } else {
        DEFAULT_ENGLISH_MODEL2VEC_MODEL
    }
}

/// Pluggable local text embedder used by hybrid search.
pub trait Embedder: Send + Sync {
    /// Stable identifier stored alongside every generated vector.
    fn model_id(&self) -> &str;

    /// Width of vectors generated by this instance.
    fn dimensions(&self) -> usize;

    /// Embeds one text into a dense vector.
    ///
    /// # Errors
    ///
    /// Returns an error when tokenization or model inference fails, or when the
    /// backend returns a vector with a different width than advertised.
    fn embed(&self, text: &str) -> Result<Vec<f32>, EmbeddingError>;
}

/// Model2Vec implementation backed by `model2vec-rs`.
#[cfg(feature = "model2vec")]
pub struct Model2VecEmbedder {
    model_id: String,
    dimensions: usize,
    model: model2vec_rs::model::StaticModel,
}

#[cfg(feature = "model2vec")]
impl Model2VecEmbedder {
    /// Loads a local path or Hugging Face model identifier.
    ///
    /// # Errors
    ///
    /// Returns an error when model assets cannot be resolved or decoded.
    pub fn from_pretrained(model_id: impl Into<String>) -> Result<Self, EmbeddingError> {
        let model_id = model_id.into();
        let model = model2vec_rs::model::StaticModel::from_pretrained(&model_id, None, None, None)
            .map_err(|error| EmbeddingError::Backend(error.to_string()))?;
        Self::from_model(model_id, model)
    }

    /// Loads a model from `cache_dir`, downloading its three Model2Vec assets
    /// there on first use unless `offline` is true.
    ///
    /// # Errors
    ///
    /// Returns [`EmbeddingError::Unavailable`] when the complete cached model
    /// is absent in offline mode, or a backend error when download/decoding fails.
    pub fn from_pretrained_cached(
        model_id: impl Into<String>,
        cache_dir: impl AsRef<Path>,
        offline: bool,
    ) -> Result<Self, EmbeddingError> {
        let model_id = model_id.into();
        let model = load_cached_model(&model_id, cache_dir.as_ref(), offline)?;
        Self::from_model(model_id, model)
    }

    /// Wraps an already loaded Model2Vec model.
    ///
    /// # Errors
    ///
    /// Returns an error if the model cannot report a non-empty vector width.
    pub fn from_model(
        model_id: impl Into<String>,
        model: model2vec_rs::model::StaticModel,
    ) -> Result<Self, EmbeddingError> {
        let dimensions = model.encode_single("").len();
        if dimensions == 0 {
            return Err(EmbeddingError::Dimensions {
                expected: DEFAULT_MODEL2VEC_DIMENSIONS,
                found: 0,
            });
        }
        Ok(Self {
            model_id: model_id.into(),
            dimensions,
            model,
        })
    }
}

/// Returns whether all model assets already exist in the local cache.
#[cfg(feature = "model2vec")]
#[must_use]
pub fn model_is_cached(model_id: &str, cache_dir: impl AsRef<Path>) -> bool {
    cached_model_files(
        &hf_hub::Cache::new(cache_dir.as_ref().to_path_buf()),
        model_id,
    )
    .is_some()
}

/// Explicitly downloads and validates one model with visible progress.
///
/// Interrupted downloads are resumed by `hf-hub` from its `.incomplete` file.
/// Callers should enforce a wall-clock timeout by running this operation in a
/// killable child process.
#[cfg(feature = "model2vec")]
pub fn install_model(model_id: &str, cache_dir: impl AsRef<Path>) -> Result<(), EmbeddingError> {
    let _ = load_cached_model(model_id, cache_dir.as_ref(), false)?;
    Ok(())
}

#[cfg(feature = "model2vec")]
impl Embedder for Model2VecEmbedder {
    fn model_id(&self) -> &str {
        &self.model_id
    }

    fn dimensions(&self) -> usize {
        self.dimensions
    }

    fn embed(&self, text: &str) -> Result<Vec<f32>, EmbeddingError> {
        let vector = self.model.encode_single(text);
        validate_dimensions(vector, self.dimensions)
    }
}

#[cfg(feature = "model2vec")]
fn load_cached_model(
    model_id: &str,
    cache_dir: &Path,
    offline: bool,
) -> Result<model2vec_rs::model::StaticModel, EmbeddingError> {
    let direct_path = Path::new(model_id);
    if direct_path.exists() {
        return model2vec_rs::model::StaticModel::from_pretrained(direct_path, None, None, None)
            .map_err(|error| EmbeddingError::Backend(error.to_string()));
    }

    let cache = hf_hub::Cache::new(cache_dir.to_path_buf());
    let files = match cached_model_files(&cache, model_id) {
        Some(files) => files,
        None if offline => {
            // Ordinary commands always pass offline = true: a search must never
            // start a half-gigabyte download on its own. Saying "offline mode"
            // blamed a switch the user never touched, which sent people looking
            // for a setting to undo instead of installing the model.
            return Err(EmbeddingError::Unavailable(format!(
                "{model_id} is not in {}, and models are never downloaded without being asked for",
                cache_dir.display()
            )));
        }
        None => download_model_files(cache, model_id)?,
    };
    let tokenizer =
        fs::read(&files.tokenizer).map_err(|error| EmbeddingError::Backend(error.to_string()))?;
    let model =
        fs::read(&files.model).map_err(|error| EmbeddingError::Backend(error.to_string()))?;
    let config =
        fs::read(&files.config).map_err(|error| EmbeddingError::Backend(error.to_string()))?;
    model2vec_rs::model::StaticModel::from_bytes(tokenizer, model, config, None)
        .map_err(|error| EmbeddingError::Backend(error.to_string()))
}

#[cfg(feature = "model2vec")]
struct ModelFiles {
    tokenizer: PathBuf,
    model: PathBuf,
    config: PathBuf,
}

#[cfg(feature = "model2vec")]
fn cached_model_files(cache: &hf_hub::Cache, model_id: &str) -> Option<ModelFiles> {
    let repository = cache.model(model_id.to_owned());
    Some(ModelFiles {
        tokenizer: repository.get("tokenizer.json")?,
        model: repository.get("model.safetensors")?,
        config: repository.get("config.json")?,
    })
}

#[cfg(feature = "model2vec")]
fn download_model_files(
    cache: hf_hub::Cache,
    model_id: &str,
) -> Result<ModelFiles, EmbeddingError> {
    fs::create_dir_all(cache.path()).map_err(|error| EmbeddingError::Backend(error.to_string()))?;
    let api = hf_hub::api::sync::ApiBuilder::from_cache(cache)
        .with_progress(true)
        .with_retries(3)
        .build()
        .map_err(|error| EmbeddingError::Unavailable(error.to_string()))?;
    let repository = api.model(model_id.to_owned());
    Ok(ModelFiles {
        tokenizer: repository
            .get("tokenizer.json")
            .map_err(|error| EmbeddingError::Unavailable(error.to_string()))?,
        model: repository
            .get("model.safetensors")
            .map_err(|error| EmbeddingError::Unavailable(error.to_string()))?,
        config: repository
            .get("config.json")
            .map_err(|error| EmbeddingError::Unavailable(error.to_string()))?,
    })
}

#[cfg(any(feature = "model2vec", test))]
fn validate_dimensions(vector: Vec<f32>, expected: usize) -> Result<Vec<f32>, EmbeddingError> {
    if vector.len() != expected {
        return Err(EmbeddingError::Dimensions {
            expected,
            found: vector.len(),
        });
    }
    Ok(vector)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dimension_validation_is_fail_closed() {
        assert!(matches!(
            validate_dimensions(vec![0.0; 3], 4),
            Err(EmbeddingError::Dimensions {
                expected: 4,
                found: 3
            })
        ));
    }

    #[test]
    fn model_selection_routes_non_ascii_languages_to_multilingual() {
        assert_eq!(
            model_id_for_text("SQLite keeps local memory"),
            DEFAULT_ENGLISH_MODEL2VEC_MODEL
        );
        assert_eq!(
            model_id_for_text("SQLite хранит локальную память"),
            DEFAULT_MODEL2VEC_MODEL
        );
    }

    #[cfg(feature = "model2vec")]
    #[test]
    fn model2vec_backend_satisfies_embedder_contract() {
        fn assert_embedder<T: Embedder>() {}
        assert_embedder::<Model2VecEmbedder>();
    }

    #[cfg(feature = "model2vec")]
    #[test]
    fn cached_loader_fails_cleanly_when_offline_model_is_absent() {
        let result = Model2VecEmbedder::from_pretrained_cached(
            DEFAULT_ENGLISH_MODEL2VEC_MODEL,
            "/definitely/missing/brain-model-cache",
            true,
        );
        assert!(matches!(result, Err(EmbeddingError::Unavailable(_))));
    }

    #[cfg(feature = "model2vec")]
    #[test]
    fn cache_probe_never_downloads_a_missing_model() {
        assert!(!model_is_cached(
            DEFAULT_ENGLISH_MODEL2VEC_MODEL,
            "/definitely/missing/brain-model-cache"
        ));
    }
}
